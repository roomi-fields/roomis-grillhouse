// grillhouse-3uv.92.1 — the regeneration of the project's references (step 3.1 of
// scripts/etapes.mjs), as `rustc --bless`, `jest -u` and `cargo insta accept`: a reference the
// project derives from the whole copy is regenerated by the circuit after a final pass whose only
// reds are its own, on the whole copy, then the final pass restricted to what it changes; the
// reviewer sees its difference with the lot; a reference the plan does not name stops the circuit.
// Witness: BPScript 320.4 (n° 9, 45 min): the fingerprint of the output (`npm run empreinte:v2 --
// --mettre-a-jour`) and the ceiling of the words (`verif-mots-de-librairie --abaisser`) count the
// whole copy, which no envelope shows (548 in the envelope against 547) and no step played; they
// alone made the final passes 5, 7 and 9 red, and the supervisor regenerated them by hand.
//
// The trial: a reference at the root, `reference.txt`, the measure of 2; a guard of the project
// judges it (its finding on `reference.txt`, a file no component of the title holds), and
// `node regenerer.mjs` writes it again. The ticket doubles the measure: the reference is red at
// the final pass alone.

// grillhouse-3uv.92.12 — a reference is declared `{ nom, commande, fichiers, tests }`, as the inputs
// of Turborepo and `rustc --bless`: `fichiers` holds paths, directories or glob patterns, `tests`
// the test files that judge it. Witness: BPScript 320.4: the fingerprint of the v2 is a directory
// of 617 files (packages/995-tools/src/empreinte-v2/<scène>.json), 262 of them changed, judged by
// packages/995-tools/test/empreinte-v2.test.ts, which the declaration could not name.

// grillhouse-3uv.92.13 — a reference also names the guards that judge it, `{ nom, commande,
// fichiers, tests, gardes }`: a finding of one of them, by the name its SARIF carries, is the
// reference's, whatever file it aims at. Witness: BPScript 320.4: a ceiling of the words exceeded
// reddens its test, which the reference names, and the guard of the project
// verif-mots-de-librairie, whose finding aims at the faulty file of code, not at the ceiling: the
// final pass did not hold reds of references alone, and the supervisor regenerated by hand.

// The trial lives out of /tmp, which the envelope replaces with an empty directory.
const ESSAIS = racineSousLaMaison('grillhouse-essais-circuit-references-');
afterAll(() => rmSync(ESSAIS, { recursive: true, force: true }));
const {
  REPO,
  BEADS,
  revenirAuDebut,
  ticket,
  scenario,
  circuit,
  essai,
  etat,
  ordre,
  commandes,
  entrees,
  gitRepo,
} = circuitEssai(ESSAIS);

const RESULTATS = path.resolve(__dirname, '../../scripts/resultats.mjs');
const NOM = 'la référence de la mesure';
const REGENERER = 'node regenerer.mjs';

// The reference of the trial on main, the project's guard judging it beside the trial's own;
// <declarer> declares it in the package.json (`grillhouse.references`).
function laReference(declarer: boolean) {
  const pkg = JSON.parse(lire(path.join(REPO, 'package.json'))) as {
    scripts: Record<string, string>;
    grillhouse?: object;
  };
  pkg.scripts.gardes = 'node garde.mjs && node garde-reference.mjs';
  if (declarer) {
    pkg.grillhouse = {
      references: [{ nom: NOM, commande: REGENERER, fichiers: ['reference.txt'] }],
    };
  }
  ecrire(path.join(REPO, 'package.json'), json(pkg));
  ecrire(path.join(REPO, 'reference.txt'), '2\n');
  ecrire(
    path.join(REPO, 'regenerer.mjs'),
    `import { writeFileSync } from 'node:fs';
import { mesure } from './packages/forms/src/index.mjs';
writeFileSync('reference.txt', mesure(2) + '\\n');
`
  );
  ecrire(
    path.join(REPO, 'garde-reference.mjs'),
    `import { readFileSync } from 'node:fs';
import { ecrireSarif } from ${JSON.stringify(RESULTATS)};
import { mesure } from './packages/forms/src/index.mjs';
const lu = readFileSync('reference.txt', 'utf8').trim();
const attendu = String(mesure(2));
if (lu !== attendu) {
  const message = 'la référence dit ' + lu + ', la mesure ' + attendu + '.';
  console.log('⛔ reference.txt:1 — ' + message);
  ecrireSarif({ garde: 'reference', constats: [{ fichier: 'reference.txt', ligne: 1, message }] });
  process.exit(1);
}
ecrireSarif({ garde: 'reference', constats: [] });
`
  );
  const git = (...a: string[]) =>
    execFileSync('git', ['-C', REPO, '-c', 'user.name=t', '-c', 'user.email=t@t', ...a]);
  git('add', '-A');
  git('commit', '-qm', 'la référence');
}

// A ticket on 000-forms whose description is <description>, its test of the double written in its
// copy, its developpeur writing the double: the run starts at that developpeur.
function leTicket(id: string, description: string) {
  const copie = ticket(id, '000-forms');
  ecrire(
    path.join(BEADS, `${id}.json`),
    json([{ id, title: `${id} — La mesure — 000-forms`, description }])
  );
  ecrire(
    path.join(copie, 'packages/forms/test/mesure.test.mjs'),
    `import { expect, it } from 'vitest';
import { mesure } from '../src/index.mjs';
it('critère 1 — mesure rend le double', () => { expect(mesure(2)).toBe(4); });
`
  );
  scenario(id, 'developpeur', `${CODE_JUSTE}passation 'Code de forms écrit.'\n`);
  return copie;
}
const lancer = (id: string) =>
  circuit([id, '--depuis', 'developpeur', '000-forms', '--contexte', 'Le double.']);
// The plan that names the reference, by its file.
const NOMMEE = `${DESCRIPTION}\n2. La référence de la mesure (\`reference.txt\`) suit le double.\n`;

describe('grillhouse-3uv.92.12 — the files of a reference', () => {
  it('critère 1 — a path, a directory or a glob pattern (*, **) covers a file, read as the inputs of Turborepo', () => {
    expect(couvertPar(['reference.txt'], 'reference.txt')).toBe(true);
    expect(couvertPar(['reference.txt'], 'autre/reference.txt')).toBe(false);
    expect(couvertPar(['src/empreinte'], 'src/empreinte/a/une.json')).toBe(true);
    expect(couvertPar(['src/empreinte/'], 'src/empreinte/une.json')).toBe(true);
    expect(couvertPar(['src/empreinte'], 'src/empreinte-v2/une.json')).toBe(false);
    expect(couvertPar(['src/empreinte/*.json'], 'src/empreinte/une.json')).toBe(true);
    expect(couvertPar(['src/empreinte/*.json'], 'src/empreinte/a/une.json')).toBe(false);
    expect(couvertPar(['src/empreinte/*.json'], 'src/empreinte/une.txt')).toBe(false);
    expect(couvertPar(['packages/**/empreinte/**'], 'packages/tools/src/empreinte/a/b.json')).toBe(
      true
    );
    expect(couvertPar(['a.txt', 'src/**/*.json'], 'src/x/y.json')).toBe(true);
    expect(couvertPar([], 'reference.txt')).toBe(false);
  });
});

describe.runIf(canWrap)(
  'grillhouse-3uv.92.1 — the regeneration of the references',
  { timeout: 300_000 },
  () => {
    afterEach(revenirAuDebut);

    it('critère 2 et 4 — regenerates a reference the plan names, plays the final pass restricted to it, and the lot carries it to the reviewer and the commit', () => {
      const id = 'demo-references-nommee';
      laReference(true);
      leTicket(id, NOMMEE);
      const r = lancer(id);
      expect(r.status, sortie(r)).toBe(0);
      // The red of the reference goes to no developpeur: the step regenerates it.
      expect(ordre(id)).toEqual(['developpeur packages/forms', 'relecteur']);
      const c = commandes(id);
      const regeneration = c.indexOf(REGENERER);
      expect(regeneration, c.join('\n')).toBeGreaterThan(0);
      // Before it, the whole final pass, red; after it, the final pass restricted to what it
      // changes, with the root's tasks.
      expect(c.slice(0, regeneration)).toContain('npm run verifier');
      expect(c.slice(regeneration + 1)[0]).toMatch(
        /^npm run verifier -- --filter=\.\.\.\[[0-9a-f]+\.\.\.[0-9a-f]+\] --filter=\/\/$/
      );
      // The step leaves its result with the circuit's, its report naming the reference and its file.
      const e = entrees(id).find(x => x.etape === 'references') as
        { rapport?: string; resultat?: { regenerees?: string[] } } | undefined;
      expect(e?.rapport).toContain(NOM);
      expect(e?.rapport).toContain('reference.txt');
      expect(e?.resultat?.regenerees).toEqual([NOM]);
      // The reviewer receives the regenerated file in the lot, and the step's report.
      const consigne = essai(id, 'relecteur-1.prompt');
      expect(consigne).toMatch(/le lot de code : [^\n;]*reference\.txt/);
      expect(consigne).toContain(REGENERER);
      // The lot on main carries the reference regenerated.
      expect(gitRepo('show', 'main:reference.txt')).toBe('4\n');
    });

    it('critère 3 — a reference the plan does not name stops the circuit at « references », named, the copy restored, for the regulator', () => {
      const id = 'demo-references-non-nommee';
      laReference(true);
      const copie = leTicket(id, DESCRIPTION);
      const r = lancer(id);
      expect(r.status, sortie(r)).toBe(ARRETS.references);
      expect(commandes(id)).toContain(REGENERER);
      const e = etat(id);
      expect(e).toMatchObject({ etape: 'references', raison: 'references', finale: true });
      expect(e?.rapport).toContain(NOM);
      expect(e?.rapport).toContain('reference.txt');
      expect(e?.rapport).toContain('ne nomme pas');
      // The regenerated file does not stay in the lot.
      expect(lire(path.join(copie, 'reference.txt'))).toBe('2\n');
      // No developpeur is relaunched on it; the stop goes to the regulator.
      expect(ordre(id).filter(x => x.startsWith('developpeur'))).toEqual([
        'developpeur packages/forms',
      ]);
      expect(ordre(id)).toContain('regulateur');
      expect(essai(id, 'regulateur-1.prompt')).toContain('reference.txt');
    });

    it('critère 1 — without the declaration, no step regenerates: the red of the reference stops at « controles »', () => {
      const id = 'demo-references-sans-declaration';
      laReference(false);
      leTicket(id, NOMMEE);
      const r = lancer(id);
      expect(r.status, sortie(r)).toBe(ARRETS.controles);
      expect(commandes(id)).not.toContain(REGENERER);
      expect(entrees(id).some(x => x.etape === 'references')).toBe(false);
      expect(etat(id)?.rapport).toContain('reference.txt');
    });

    it('critère 2, 3 et 4 — a fingerprint by scene, a directory under a pattern judged by its test file, regenerated in part: the red of its test goes to the step, each file changed covered by the pattern', () => {
      const id = 'demo-references-empreinte';
      const EMPREINTE = "l'empreinte des scènes";
      const SCENES = { zero: 0, un: 1, deux: 2 };
      const pkg = JSON.parse(lire(path.join(REPO, 'package.json'))) as { grillhouse?: object };
      pkg.grillhouse = {
        references: [
          {
            nom: EMPREINTE,
            commande: 'node empreinte.mjs',
            fichiers: ['packages/binder/empreinte/*.json'],
            tests: ['packages/binder/test/empreinte.test.mjs'],
          },
        ],
      };
      ecrire(path.join(REPO, 'package.json'), json(pkg));
      for (const [scene, n] of Object.entries(SCENES)) {
        ecrire(path.join(REPO, `packages/binder/empreinte/${scene}.json`), json({ mesure: n }));
      }
      ecrire(
        path.join(REPO, 'empreinte.mjs'),
        `import { writeFileSync } from 'node:fs';
import { mesure } from './packages/forms/src/index.mjs';
for (const [scene, n] of Object.entries(${JSON.stringify(SCENES)})) {
  writeFileSync('packages/binder/empreinte/' + scene + '.json', JSON.stringify({ mesure: mesure(n) }, null, 2) + '\\n');
}
`
      );
      ecrire(
        path.join(REPO, 'packages/binder/test/empreinte.test.mjs'),
        `import { readFileSync } from 'node:fs';
import { expect, it } from 'vitest';
import { mesure } from '../../forms/src/index.mjs';
it("l'empreinte de chaque scène suit la mesure", () => {
  for (const [scene, n] of Object.entries(${JSON.stringify(SCENES)})) {
    const lu = JSON.parse(readFileSync(new URL('../empreinte/' + scene + '.json', import.meta.url), 'utf8'));
    expect(lu.mesure, scene).toBe(mesure(n));
  }
});
`
      );
      const git = (...a: string[]) =>
        execFileSync('git', ['-C', REPO, '-c', 'user.name=t', '-c', 'user.email=t@t', ...a]);
      git('add', '-A');
      git('commit', '-qm', "l'empreinte");
      leTicket(id, `${DESCRIPTION}\n2. ${EMPREINTE} suit le double.\n`);
      const r = lancer(id);
      expect(r.status, sortie(r)).toBe(0);
      // The red of the test that judges the reference, in a package out of the title, goes to no
      // developpeur: the step regenerates it.
      expect(ordre(id)).toEqual(['developpeur packages/forms', 'relecteur']);
      expect(commandes(id)).toContain('node empreinte.mjs');
      const e = entrees(id).find(x => x.etape === 'references') as
        { resultat?: { regenerees?: string[]; fichiers?: string[] } } | undefined;
      expect(e?.resultat?.regenerees).toEqual([EMPREINTE]);
      // A part of the scenes changes, each file changed covered by the pattern.
      expect([...(e?.resultat?.fichiers ?? [])].sort()).toEqual([
        'packages/binder/empreinte/deux.json',
        'packages/binder/empreinte/un.json',
      ]);
      expect(JSON.parse(gitRepo('show', 'main:packages/binder/empreinte/deux.json'))).toEqual({
        mesure: 4,
      });
    });

    it('grillhouse-3uv.92.13 critère 1 et 2 — a ceiling exceeded reddens its test and a guard whose finding aims at a file of code: the guard named by the reference, 3.1 regenerates, then the restricted pass is green', () => {
      const id = 'demo-references-plafond';
      const PLAFOND = 'le plafond des mots';
      const GARDE_DES_MOTS = 'verif-mots-de-librairie';
      const pkg = JSON.parse(lire(path.join(REPO, 'package.json'))) as {
        scripts: Record<string, string>;
        grillhouse?: object;
      };
      pkg.scripts.gardes = 'node garde.mjs && node garde-mots.mjs';
      pkg.grillhouse = {
        references: [
          {
            nom: PLAFOND,
            commande: 'node abaisser.mjs',
            fichiers: ['packages/binder/plafond.txt'],
            tests: ['packages/binder/test/plafond.test.mjs'],
            gardes: [GARDE_DES_MOTS],
          },
        ],
      };
      ecrire(path.join(REPO, 'package.json'), json(pkg));
      ecrire(path.join(REPO, 'packages/binder/plafond.txt'), '2\n');
      ecrire(
        path.join(REPO, 'abaisser.mjs'),
        `import { writeFileSync } from 'node:fs';
import { mesure } from './packages/forms/src/index.mjs';
writeFileSync('packages/binder/plafond.txt', mesure(2) + '\\n');
`
      );
      ecrire(
        path.join(REPO, 'packages/binder/test/plafond.test.mjs'),
        `import { readFileSync } from 'node:fs';
import { expect, it } from 'vitest';
import { mesure } from '../../forms/src/index.mjs';
it('le compte ne dépasse pas le plafond', () => {
  const plafond = Number(readFileSync(new URL('../plafond.txt', import.meta.url), 'utf8'));
  expect(mesure(2)).toBeLessThanOrEqual(plafond);
});
`
      );
      // The guard of the words, as BPScript's: its finding aims at the file of code that counts
      // too many, a file of the component of the title, not at the ceiling.
      ecrire(
        path.join(REPO, 'garde-mots.mjs'),
        `import { readFileSync } from 'node:fs';
import { ecrireSarif } from ${JSON.stringify(RESULTATS)};
import { mesure } from './packages/forms/src/index.mjs';
const plafond = Number(readFileSync('packages/binder/plafond.txt', 'utf8'));
const garde = ${JSON.stringify(GARDE_DES_MOTS)};
if (mesure(2) > plafond) {
  const message = 'forms ' + mesure(2) + ' > ' + plafond;
  console.log('⛔ packages/forms/src/index.mjs — ' + message);
  ecrireSarif({ garde, constats: [{ fichier: 'packages/forms/src/index.mjs', message }] });
  process.exit(1);
}
ecrireSarif({ garde, constats: [] });
`
      );
      const git = (...a: string[]) =>
        execFileSync('git', ['-C', REPO, '-c', 'user.name=t', '-c', 'user.email=t@t', ...a]);
      git('add', '-A');
      git('commit', '-qm', 'le plafond');
      leTicket(id, `${DESCRIPTION}\n2. ${PLAFOND} suit le double.\n`);
      const r = lancer(id);
      expect(r.status, sortie(r)).toBe(0);
      // The finding of the guard on the code of forms goes to no developpeur: the step regenerates.
      expect(ordre(id)).toEqual(['developpeur packages/forms', 'relecteur']);
      const c = commandes(id);
      const regeneration = c.indexOf('node abaisser.mjs');
      expect(regeneration, c.join('\n')).toBeGreaterThan(0);
      expect(c.slice(regeneration + 1)[0]).toMatch(
        /^npm run verifier -- --filter=\.\.\.\[[0-9a-f]+\.\.\.[0-9a-f]+\] --filter=\/\/$/
      );
      const e = entrees(id).find(x => x.etape === 'references') as
        { resultat?: { regenerees?: string[]; fichiers?: string[] } } | undefined;
      expect(e?.resultat?.regenerees).toEqual([PLAFOND]);
      expect(e?.resultat?.fichiers).toEqual(['packages/binder/plafond.txt']);
      expect(gitRepo('show', 'main:packages/binder/plafond.txt')).toBe('4\n');
    });
  }
);
