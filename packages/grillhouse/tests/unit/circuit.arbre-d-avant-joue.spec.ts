// Out of every temporary directory, beside the package, as the copies under `.claude/worktrees` lie:
// the test measures a copy that no temporary directory holds, so it cannot lie under one (the
// decision of grillhouse-44b.4.6, question 1). The folder is named by the pid of its test; the
// `afterAll` removes it, and a killed test leaves it, which the next run sweeps below.
const PAQUET = path.resolve(__dirname, '../..');
const PREFIXE = '.essai-3e2.3-';
const DUREE_MAX_MS = 60 * 60 * 1000;
const vivant = (pid: number) => {
  try {
    process.kill(pid, 0);
    return true;
  } catch (e) {
    return (e as NodeJS.ErrnoException).code === 'EPERM';
  }
};
const DEHORS = mkdtempSync(path.join(PAQUET, `${PREFIXE}${process.pid}-`));
afterAll(() => rmSync(DEHORS, { recursive: true, force: true }));
// What a killed run left: a folder whose process is gone, or older than the test can last.
beforeAll(() => {
  for (const nom of readdirSync(PAQUET)) {
    const pid = Number(nom.match(/^\.essai-3e2\.3-(\d+)-/)?.[1] ?? Number.NaN);
    const chemin = path.join(PAQUET, nom);
    if (!nom.startsWith(PREFIXE) || chemin === DEHORS) {
      continue;
    }
    const vieux = Date.now() - statSync(chemin).mtimeMs > DUREE_MAX_MS;
    if (Number.isNaN(pid) || !vivant(pid) || vieux) {
      rmSync(chemin, { recursive: true, force: true });
    }
  }
});
const ESSAIS = mkdtempSync(path.join(tmpdir(), 'arbre-joue-'));
afterAll(() => rmSync(ESSAIS, { recursive: true, force: true }));

let restaurer: () => void = () => {};
let journal = '';
beforeAll(() => {
  journal = path.join(ESSAIS, 'journal');
  restaurer = avecFauxCargo(installerFauxCargo(ESSAIS), journal);
});
afterAll(() => restaurer());

const ecrire = (racine: string, f: string, texte: string) => {
  mkdirSync(path.dirname(path.join(racine, f)), { recursive: true });
  writeFileSync(path.join(racine, f), texte);
};
const git = (racine: string, ...args: string[]) => {
  const r = spawnSync('git', ['-C', racine, ...args], { encoding: 'utf8' });
  expect(r.status, r.stderr).toBe(0);
};

const CIBLE = 'crates/service/tests/electra_reimport.rs';
const CARGO: Record<string, string> = {
  'Cargo.toml': '[workspace]\nmembers = ["crates/service"]\nresolver = "2"\n',
  'Cargo.lock': '# This file is automatically @generated by Cargo.\nversion = 3\n',
  'crates/service/Cargo.toml': '[package]\nname = "service"\nversion = "0.1.0"\nedition = "2021"\n',
  'crates/service/src/lib.rs': 'pub fn un() -> i32 { 1 }\n',
  [CIBLE]: '#[test]\nfn ancien() {}\n',
};

// A repository of cargo under <dans>, its `Cargo.lock` tracked, the target changed by the lot.
function depotCargo(dans: string) {
  const racine = mkdtempSync(path.join(dans, 'depot-'));
  declarerLesLangages(racine, { 'crates/service': 'cargo' });
  for (const [f, texte] of Object.entries(CARGO)) {
    ecrire(racine, f, texte);
  }
  ecrire(racine, '.gitignore', 'target/\nnode_modules/\n');
  git(racine, 'init', '-q');
  git(racine, 'add', '-A');
  git(racine, '-c', 'user.name=t', '-c', 'user.email=t@t', 'commit', '-q', '-m', 'HEAD');
  ecrire(racine, CIBLE, `${CARGO[CIBLE]}#[test]\nfn neuf() {}\n`);
  const tmp = mkdtempSync(path.join(ESSAIS, 'ticket-'));
  return { racine, ctx: { copie: racine, tmp } as Ctx };
}

describe('grillhouse-3e2.3 — the tree played for real, in cargo', () => {
  it('criterion 5: the cargo target directory of a tree is the copy’s, a copy out of the temporary directory too', () => {
    const { racine, ctx } = depotCargo(DEHORS);
    let env: Record<string, string> = {};
    avecLesVersionsDAvant(ctx, [CIBLE], (_a, _l, arbres) => {
      env = (arbres.get(CIBLE) as Arbre).env;
    });
    // The copy builds in its own `target/`; the tree, which lies in the temporary directory,
    // builds there too, not in a cache of its own root.
    expect(env.CARGO_TARGET_DIR).toBe(path.join(racine, 'target'));
  });

  it('criteria 2, 5 and 6: the launcher of cargo plays the tree (no refusal of a Cargo.lock git does not track) and gives the file’s report', () => {
    const { racine, ctx } = depotCargo(DEHORS);
    let code = -1;
    let rapport: { fichier: string; tests: { nom: string; etat: string }[] }[] = [];
    let racineDeLArbre = '';
    avecLesVersionsDAvant(ctx, [CIBLE], (_a, _l, arbres) => {
      const arbre = arbres.get(CIBLE) as Arbre;
      racineDeLArbre = arbre.racine;
      const resultats = mkdtempSync(path.join(ESSAIS, 'resultats-'));
      // The body of the task of the crate (grillhouse-44b.5): `tester` hands it to Turborepo, which
      // a tree without a graph does not run.
      code = (lancer as (...a: unknown[]) => number)('tests-du-paquet', [CIBLE], {
        racine: arbre.racine,
        env: { ...process.env, ...arbre.env, [RESULTATS]: resultats },
      });
      rapport = (
        moduleCargo as unknown as { verdict: (d: string) => { rapports: typeof rapport } }
      ).verdict(resultats).rapports;
    });
    expect(code).toBe(0);
    // The report is the copy’s by the change of root alone, the file under its own name.
    expect(rapport.map(r => path.relative(racineDeLArbre, r.fichier))).toContain(CIBLE);
    expect(rapport.map(r => r.fichier)).not.toContain(path.join(racine, CIBLE));
    expect(existsSync(racineDeLArbre)).toBe(false);
  });
});
