// grillhouse-3e2.3 — the tree of HEAD’s version is played for real, not only built: the launcher of
// the language runs in it and gives back its report; the copy lies out of the temporary directory
// (a copy under `.claude/worktrees`, the real case). A tree left by a killed process is a night
// test (./circuit.arbre-d-avant-tue.nuit.test.ts).
// Medium tests: a local process, the fake cargo (./langages/cargo/faux-cargo.ts), a repository of
// trial. The review of grillhouse-3e2.3, finding 1.
