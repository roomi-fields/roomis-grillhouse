import { execFileSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { afterAll, describe, expect, it } from 'vitest';
import { elementsDuLot } from '../../scripts/elements-du-lot.mjs';

// The elements of a lot (scripts/elements-du-lot.mjs), decision 2 of grillhouse-3uv.95, Romain
// (2026-10-23): « il faut que le relecteur valide vraiment la conformité à l'architecture de tout
// ce qu'il y a de nouveau/changé ». As API Extractor's report and its diff, read line by line, and
// a review that asks a word on every changed file, the circuit lists each element the lot adds,
// changes or removes (a function, a class, a type, an interface, a constant at the top of a module,
// an export), with its package, its file and line and whether its package's entry exports it:
// TypeScript's language service reads the declarations and the exports (the mechanism of
// scripts/references-par-les-types.mjs), the git diff of the lot says which lines moved, and the
// diff of the API reports (scripts/interfaces-contre-code.mjs) names the exports that change.

const ESSAIS = mkdtempSync(path.join(tmpdir(), 'elements-du-lot-'));
afterAll(() => rmSync(ESSAIS, { recursive: true, force: true }));

type Element = {
  id: string;
  nom: string;
  genre: string;
  statut: string;
  paquet: string;
  fichier: string;
  ligne: number;
  exporte: boolean;
};
type Liste = {
  etat: string;
  raison: string | null;
  elements: Element[];
  horsDuService: string[];
  service?: string | null;
};
// The elements of the lot of <copie> between the commits of <lot>.
const lister = (copie: string, lot: { avant: string; apres: string }) =>
  elementsDuLot(copie, lot) as Liste;

const ecrire = (racine: string, files: Record<string, string | null>) => {
  for (const [rel, text] of Object.entries(files)) {
    const f = path.join(racine, rel);
    if (text === null) {
      rmSync(f);
      continue;
    }
    mkdirSync(path.dirname(f), { recursive: true });
    writeFileSync(f, text);
  }
};
const git = (racine: string, ...a: string[]) =>
  execFileSync('git', ['-C', racine, '-c', 'user.name=t', '-c', 'user.email=t@t', ...a], {
    encoding: 'utf8',
  }).trim();
const commit = (racine: string) => {
  git(racine, 'add', '-A');
  git(racine, 'commit', '-qm', 'lot');
  return git(racine, 'rev-parse', 'HEAD');
};
const lignes = (...l: string[]) => `${l.join('\n')}\n`;

// The API report of 000-forms, as API Extractor writes it, with the declarations <decls>.
const rapport = (...decls: string[]) =>
  lignes(
    '## API Report File for "000-forms"',
    '',
    '> Do not edit this file. It is a report generated by [API Extractor](https://api-extractor.com/).',
    '',
    '```ts',
    '',
    ...decls.flatMap(d => ['// @public', d, '']),
    '```'
  );
const TSCONFIG = JSON.stringify({
  compilerOptions: {
    target: 'ES2022',
    module: 'ESNext',
    moduleResolution: 'Bundler',
    allowImportingTsExtensions: true,
    noEmit: true,
    strict: true,
    types: [],
  },
  include: ['src', 'test'],
});

// 000-forms, a TypeScript package whose entry is its source; outils, a package of tools without a
// tsconfig.json, that the language service does not read.
const AVANT = {
  'package.json': JSON.stringify({ name: 'essai', private: true, workspaces: ['packages/*'] }),
  'packages/forms/package.json': JSON.stringify({
    name: '000-forms',
    type: 'module',
    exports: { '.': './src/index.ts' },
  }),
  'packages/forms/tsconfig.json': TSCONFIG,
  'packages/forms/src/index.ts': lignes(
    "export { aire } from './interne.ts';",
    'export function mesure(x: number): number {',
    '  return x;',
    '}',
    'export function retire(x: number): number {',
    '  return -x;',
    '}',
    'export type Forme = { readonly cote: number };'
  ),
  'packages/forms/src/interne.ts': lignes(
    'const FACTEUR = 2;',
    'function double(x: number): number {',
    '  return x * FACTEUR;',
    '}',
    'export function aire(c: number): number {',
    '  return double(c) * c;',
    '}',
    'export function stable(): number {',
    '  return 1;',
    '}'
  ),
  'packages/forms/src/ancien.ts': lignes('export function vieux(): number {', '  return 0;', '}'),
  'packages/forms/test/index.test.ts': lignes('export const essai = 1;'),
  'packages/forms/docs/INTERFACE.api.md': rapport(
    'export function aire(c: number): number;',
    'export type Forme = {\n    readonly cote: number;\n};',
    'export function mesure(x: number): number;',
    'export function retire(x: number): number;'
  ),
  'packages/outils/package.json': JSON.stringify({ name: 'outils', type: 'module' }),
  'packages/outils/src/outil.mjs': lignes('export const outil = 1;'),
};

// The lot: mesure changed, retire removed from the entry and its report, neuve added and exported,
// stable newly re-exported by the entry, FACTEUR changed and aide added inside the package, the
// file ancien.ts removed, a test changed, the report of Forme regenerated while its source line
// stays, and the tool of outils changed.
const LOT = {
  'packages/forms/src/index.ts': lignes(
    "export { aire } from './interne.ts';",
    "export { stable } from './interne.ts';",
    'export function mesure(x: number): number {',
    '  return 2 * x;',
    '}',
    'export function neuve(): string {',
    "  return 'n';",
    '}',
    'export type Forme = { readonly cote: number };'
  ),
  'packages/forms/src/interne.ts': lignes(
    'const FACTEUR = 3;',
    'function double(x: number): number {',
    '  return x * FACTEUR;',
    '}',
    'export function aire(c: number): number {',
    '  return double(c) * c;',
    '}',
    'export function stable(): number {',
    '  return 1;',
    '}',
    'function aide(): number {',
    '  return 0;',
    '}'
  ),
  'packages/forms/src/ancien.ts': null,
  'packages/forms/test/index.test.ts': lignes('export const essai = 2;'),
  'packages/forms/docs/INTERFACE.api.md': rapport(
    'export function aire(c: number): number;',
    'export type Forme = {\n    readonly cote: number;\n    readonly nom?: string;\n};',
    'export function mesure(x: number): number;',
    'export function neuve(): string;',
    'export function stable(): number;'
  ),
  'packages/outils/src/outil.mjs': lignes('export const outil = 2;'),
};

describe('the elements of a lot', () => {
  const racine = mkdtempSync(path.join(ESSAIS, 'depot-'));
  ecrire(racine, AVANT);
  git(racine, 'init', '-q', '-b', 'main');
  const avant = commit(racine);
  ecrire(racine, LOT);
  const apres = commit(racine);
  const liste = lister(racine, { avant, apres });
  const ligneDuRapport = LOT['packages/forms/docs/INTERFACE.api.md']
    .split('\n')
    .findIndex(l => l.startsWith('export type Forme'));

  it('lists each element new, changed or removed, with its package, its file and line, and whether its package exports it', () => {
    expect(liste.etat).toBe('fait');
    expect(liste.elements).toEqual([
      {
        id: 'packages/forms/docs/INTERFACE.api.md#Forme',
        nom: 'Forme',
        genre: 'type',
        statut: 'changé',
        paquet: '000-forms',
        fichier: 'packages/forms/docs/INTERFACE.api.md',
        ligne: ligneDuRapport + 1,
        exporte: true,
      },
      {
        id: 'packages/forms/src/ancien.ts#vieux',
        nom: 'vieux',
        genre: 'fonction',
        statut: 'supprimé',
        paquet: '000-forms',
        fichier: 'packages/forms/src/ancien.ts',
        ligne: 1,
        exporte: false,
      },
      {
        id: 'packages/forms/src/index.ts#stable',
        nom: 'stable',
        genre: 'export',
        statut: 'neuf',
        paquet: '000-forms',
        fichier: 'packages/forms/src/index.ts',
        ligne: 2,
        exporte: true,
      },
      {
        id: 'packages/forms/src/index.ts#mesure',
        nom: 'mesure',
        genre: 'fonction',
        statut: 'changé',
        paquet: '000-forms',
        fichier: 'packages/forms/src/index.ts',
        ligne: 3,
        exporte: true,
      },
      {
        id: 'packages/forms/src/index.ts#retire',
        nom: 'retire',
        genre: 'fonction',
        statut: 'supprimé',
        paquet: '000-forms',
        fichier: 'packages/forms/src/index.ts',
        ligne: 5,
        exporte: true,
      },
      {
        id: 'packages/forms/src/index.ts#neuve',
        nom: 'neuve',
        genre: 'fonction',
        statut: 'neuf',
        paquet: '000-forms',
        fichier: 'packages/forms/src/index.ts',
        ligne: 6,
        exporte: true,
      },
      {
        id: 'packages/forms/src/interne.ts#FACTEUR',
        nom: 'FACTEUR',
        genre: 'constante',
        statut: 'changé',
        paquet: '000-forms',
        fichier: 'packages/forms/src/interne.ts',
        ligne: 1,
        exporte: false,
      },
      {
        id: 'packages/forms/src/interne.ts#aide',
        nom: 'aide',
        genre: 'fonction',
        statut: 'neuf',
        paquet: '000-forms',
        fichier: 'packages/forms/src/interne.ts',
        ligne: 11,
        exporte: false,
      },
    ]);
  });

  it('leaves out the tests and what the lot does not change', () => {
    const noms = liste.elements.map(e => e.nom);
    for (const nom of ['essai', 'aire', 'double']) {
      expect(noms).not.toContain(nom);
    }
    // stable: unchanged where it is declared, new only as the entry's export.
    expect(liste.elements.filter(e => e.nom === 'stable').map(e => e.fichier)).toEqual([
      'packages/forms/src/index.ts',
    ]);
  });

  it('names the changed sources the language service does not read, a package without tsconfig.json', () => {
    expect(liste.horsDuService).toEqual(['packages/outils/src/outil.mjs']);
    // The service ran: no tsconfig.json reads that file.
    expect(liste.service).toBeNull();
  });

  it('lists nothing for a lot that changes no source', () => {
    expect(lister(racine, { avant: apres, apres })).toEqual({
      etat: 'fait',
      raison: null,
      elements: [],
      horsDuService: [],
      service: null,
    });
  });

  it('lists the element of a file whose path is not ASCII, which git quotes in a diff', () => {
    const autre = mkdtempSync(path.join(ESSAIS, 'depot-'));
    ecrire(autre, {
      'package.json': AVANT['package.json'],
      'packages/a/package.json': JSON.stringify({ name: 'a', type: 'module' }),
      'packages/a/tsconfig.json': TSCONFIG,
      'packages/a/src/détail.ts': lignes('export const taille = 1;'),
    });
    git(autre, 'init', '-q', '-b', 'main');
    const a = commit(autre);
    ecrire(autre, { 'packages/a/src/détail.ts': lignes('export const taille = 2;') });
    const b = commit(autre);
    expect(lister(autre, { avant: a, apres: b }).elements.map(e => [e.id, e.statut])).toEqual([
      ['packages/a/src/détail.ts#taille', 'changé'],
    ]);
  });

  it('says why the language service could not run, no tsconfig.json in the components', () => {
    const autre = mkdtempSync(path.join(ESSAIS, 'depot-'));
    ecrire(autre, {
      'package.json': AVANT['package.json'],
      'packages/outils/package.json': AVANT['packages/outils/package.json'],
      'packages/outils/src/outil.mjs': AVANT['packages/outils/src/outil.mjs'],
    });
    git(autre, 'init', '-q', '-b', 'main');
    const a = commit(autre);
    ecrire(autre, { 'packages/outils/src/outil.mjs': LOT['packages/outils/src/outil.mjs'] });
    const b = commit(autre);
    const r = lister(autre, { avant: a, apres: b });
    expect(r.horsDuService).toEqual(['packages/outils/src/outil.mjs']);
    expect(r.service).toMatch(/tsconfig\.json/);
  });

  it('reads an export from the entry by the language service, a report not yet regenerated', () => {
    const autre = mkdtempSync(path.join(ESSAIS, 'depot-'));
    ecrire(autre, {
      'package.json': AVANT['package.json'],
      'packages/a/package.json': JSON.stringify({ name: 'a', exports: { '.': './src/index.ts' } }),
      'packages/a/tsconfig.json': TSCONFIG,
      'packages/a/src/index.ts': lignes("export * from './x.ts';"),
      'packages/a/src/x.ts': lignes('export function f(): number {', '  return 1;', '}'),
    });
    git(autre, 'init', '-q', '-b', 'main');
    const a = commit(autre);
    ecrire(autre, {
      'packages/a/src/x.ts': lignes(
        'export function f(): number {',
        '  return 2;',
        '}',
        'export function h(): number {',
        '  return 3;',
        '}',
        'function k(): void {}'
      ),
    });
    const b = commit(autre);
    expect(
      lister(autre, { avant: a, apres: b }).elements.map(e => [e.nom, e.statut, e.exporte])
    ).toEqual([
      ['f', 'changé', true],
      ['h', 'neuf', true],
      ['k', 'neuf', false],
    ]);
  });

  it('says why when git cannot read the lot', () => {
    const r = lister(racine, { avant: 'nulle-part', apres });
    expect(r.etat).toBe('impossible');
    expect(r.raison).toMatch(/nulle-part/);
    expect(r.elements).toEqual([]);
  });
});
