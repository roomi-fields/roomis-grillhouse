// @poste: sccache
// grillhouse-3e2.3, criterion 5 — a tree left by a killed process is removed by the next run.
// A large test (a repository of trial, a node process killed by a signal): a night test. The
// review of grillhouse-3e2.3, finding 1.
import { spawn, spawnSync } from 'node:child_process';
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { avecFauxCargo, installerFauxCargo } from './langages/cargo/faux-cargo.js';
import { declarerLesLangages } from '@roomi-fields/grillhouse-matiere/test-fixtures';
import * as activites from '../../scripts/activites.mjs';

type Arbre = { racine: string; env: Record<string, string> };
type Ctx = { copie: string; tmp: string };
const avecLesVersionsDAvant = activites.avecLesVersionsDAvant as (
  ctx: Ctx,
  fichiers: string[],
  jouer: (
    avant: Map<string, string>,
    lus: Map<string, string[]>,
    arbres: Map<string, Arbre>
  ) => unknown
) => unknown;
const ACTIVITES = path.resolve(__dirname, '../../scripts/activites.mjs');

// Out of every temporary directory, beside the package, as the copies under `.claude/worktrees` lie.
const DEHORS = mkdtempSync(path.resolve(__dirname, '../../.essai-3e2.3-tue-'));
afterAll(() => rmSync(DEHORS, { recursive: true, force: true }));
const ESSAIS = mkdtempSync(path.join(tmpdir(), 'arbre-tue-'));
afterAll(() => rmSync(ESSAIS, { recursive: true, force: true }));

// The child process inherits the fake cargo (`cargo metadata` of the tree).
let restaurer: () => void = () => {};
beforeAll(() => {
  restaurer = avecFauxCargo(installerFauxCargo(ESSAIS), path.join(ESSAIS, 'journal'));
});
afterAll(() => restaurer());

const ecrire = (racine: string, f: string, texte: string) => {
  mkdirSync(path.dirname(path.join(racine, f)), { recursive: true });
  writeFileSync(path.join(racine, f), texte);
};
const git = (racine: string, ...args: string[]) => {
  const r = spawnSync('git', ['-C', racine, ...args], { encoding: 'utf8' });
  expect(r.status, r.stderr).toBe(0);
};
const lister = (dossier: string): string[] => readdirSync(dossier).sort();

const CIBLE = 'crates/service/tests/electra_reimport.rs';
const CARGO: Record<string, string> = {
  'Cargo.toml': '[workspace]\nmembers = ["crates/service"]\nresolver = "2"\n',
  'Cargo.lock': '# This file is automatically @generated by Cargo.\nversion = 3\n',
  'crates/service/Cargo.toml': '[package]\nname = "service"\nversion = "0.1.0"\nedition = "2021"\n',
  'crates/service/src/lib.rs': 'pub fn un() -> i32 { 1 }\n',
  [CIBLE]: '#[test]\nfn ancien() {}\n',
};

describe('grillhouse-3e2.3 — a tree left by a killed process', () => {
  // A child process builds the tree, says where, and stays inside <jouer> as a long test does.
  async function tuerLeProprietaire(
    signal: NodeJS.Signals,
    fichier: string,
    langages: Record<string, string>,
    fichiers: Record<string, string>
  ) {
    const racine = mkdtempSync(path.join(DEHORS, 'depot-'));
    declarerLesLangages(racine, langages);
    for (const [f, texte] of Object.entries(fichiers)) {
      ecrire(racine, f, texte);
    }
    git(racine, 'init', '-q');
    git(racine, 'add', '-A');
    git(racine, '-c', 'user.name=t', '-c', 'user.email=t@t', 'commit', '-q', '-m', 'HEAD');
    ecrire(racine, fichier, `${fichiers[fichier]}// le lot\n`);
    const tmp = mkdtempSync(path.join(ESSAIS, 'ticket-'));
    const script = `
      import { avecLesVersionsDAvant } from ${JSON.stringify(ACTIVITES)};
      avecLesVersionsDAvant({ copie: ${JSON.stringify(racine)}, tmp: ${JSON.stringify(tmp)} }, [${JSON.stringify(fichier)}], (_a, _l, arbres) => {
        process.stdout.write('ARBRE ' + [...arbres.values()][0].racine + '\\n');
        Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, 60000);
      });
    `;
    const enfant = spawn(process.execPath, ['--input-type=module', '-e', script], {
      stdio: ['ignore', 'pipe', 'inherit'],
    });
    const arbre = await new Promise<string>((resolve, reject) => {
      let vu = '';
      enfant.stdout.on('data', d => {
        vu += d;
        const m = /ARBRE (.+)\n/.exec(vu);
        if (m) {
          resolve(m[1]);
        }
      });
      enfant.on('exit', () => reject(new Error(`l’enfant s’est arrêté avant l’arbre : ${vu}`)));
    });
    expect(existsSync(arbre)).toBe(true);
    const fini = new Promise(r => enfant.on('exit', r));
    enfant.kill(signal);
    await Promise.race([fini, new Promise(r => setTimeout(r, 20000))]);
    enfant.kill('SIGKILL');
    await fini;
    return { racine, tmp, arbre };
  }

  it.each([
    ['SIGKILL', 'SIGKILL' as const],
    ['SIGTERM', 'SIGTERM' as const],
  ])(
    'criterion 5, cargo (%s): the next run removes the tree the dead owner left, and leaves nothing',
    async (_n, signal) => {
      const { racine, tmp, arbre } = await tuerLeProprietaire(
        signal,
        CIBLE,
        { 'crates/service': 'cargo' },
        CARGO
      );
      avecLesVersionsDAvant({ copie: racine, tmp }, [CIBLE], () => undefined);
      expect(existsSync(arbre)).toBe(false);
      expect(lister(tmp)).toEqual([]);
      expect(readFileSync(path.join(racine, CIBLE), 'utf8')).toBe(`${CARGO[CIBLE]}// le lot\n`);
    },
    60000
  );

  it('criterion 5, python (SIGKILL): the next run removes the tree the dead owner left, and leaves nothing', async () => {
    const f = 'site/tests/test_pages.py';
    const fichiers = {
      'package.json': JSON.stringify({ name: 'p', private: true }),
      'site/pyproject.toml': '[project]\nname = "site"\nversion = "0.1.0"\n',
      [f]: 'def test_ancien():\n    assert True\n',
    };
    const { racine, tmp, arbre } = await tuerLeProprietaire(
      'SIGKILL',
      f,
      { site: 'python' },
      fichiers
    );
    avecLesVersionsDAvant({ copie: racine, tmp }, [f], () => undefined);
    expect(existsSync(arbre)).toBe(false);
    expect(lister(tmp)).toEqual([]);
  }, 60000);
});
